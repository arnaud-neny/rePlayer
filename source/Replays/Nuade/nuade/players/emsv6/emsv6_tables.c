// Past the end of the data the replayer reads whatever follows its code; read as 0.

uint16_t e6_period_table(int finetune, int note) {
    const int index = finetune * NOTES + note;
    if (index == -1) {
        return k_note_below_first;
    }
    return index >= 0 && index < FINETUNES * NOTES ? k_periods[index / NOTES][index % NOTES] : 0;
}
